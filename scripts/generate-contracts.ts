import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import { silentLogger } from '@levelhead/core'
import { buildApp } from '../apps/server/src/app.ts'
import { loadConfig } from '../apps/server/src/config.ts'
import {
  FixedClock,
  MemoryEventStore,
  ScriptedConductor,
  ScriptedEvaluator,
  SeqIds,
} from '../apps/cli/src/testing/fakes.ts'

const OPENAPI_PATH = 'apps/web/src/api/openapi.gen.json'
const TYPES_PATH = 'apps/web/src/api/schema.gen.ts'

const HEADER = `// Generated by \`bun run contracts:generate\` from the server's own TypeBox schemas.
// Never edited by hand: the schemas in packages/contracts are authoritative (ADR-006).
`

async function write(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, content, 'utf8')
}

async function readOrEmpty(path: string): Promise<string> {
  try {
    return await readFile(path, 'utf8')
  } catch {
    return ''
  }
}

const store = new MemoryEventStore()
const app = await buildApp(loadConfig({ NODE_ENV: 'test', LOG_LEVEL: 'fatal' }), {
  storeFor: () => store,
  clock: new FixedClock(),
  ids: new SeqIds(),
  conductor: new ScriptedConductor([]),
  evaluator: new ScriptedEvaluator([]),
  ceilings: { sessionCostUsd: 1, sessionTokens: 1_000, modelCallsPerTurn: 1 },
  logger: silentLogger,
  queue: null,
  retrieval: null,
})
await app.ready()

const document = `${JSON.stringify(app.swagger(), null, 2)}\n`
const types = `${HEADER}${astToString(await openapiTS(app.swagger() as never))}`
await app.close()

// `--check` is what makes stale committed output a CI failure rather than a surprise (ADR-006).
if (process.argv.includes('--check')) {
  const stale: string[] = []
  for (const [path, fresh] of [
    [OPENAPI_PATH, document],
    [TYPES_PATH, types],
  ] as const) {
    if ((await readOrEmpty(path)) !== fresh) stale.push(path)
  }
  if (stale.length > 0) {
    process.stderr.write(
      `generated contracts are stale: ${stale.join(', ')}\nrun: bun run contracts:generate\n`,
    )
    process.exit(1)
  }
  process.stdout.write('generated contracts are up to date\n')
} else {
  await write(OPENAPI_PATH, document)
  await write(TYPES_PATH, types)
  process.stdout.write(`wrote ${OPENAPI_PATH} and ${TYPES_PATH}\n`)
}
